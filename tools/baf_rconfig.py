#!/usr/bin/env python3
"""Write the per-account R globals that scripts/30-bracket-at-fill.das reads.

R is never typed into a script. This reads the R-CONFIG table in the private Trading
PREFERENCES (the single source of truth for R per account) and writes
scripts/local/baf-rconfig.das, which is gitignored because it holds account IDs.
Paste that file at the TOP of DAS: Setup > Hotkey > Scripts > Desktop Load Script.

    python3 tools/baf_rconfig.py            write the file
    python3 tools/baf_rconfig.py --check    report what would be written, IDs masked

Every one of the three slots is always written. An unused slot holds "none" and R 0,
because a DAS variable assigned "" stays unregistered (grammar.md 2.5).
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

PREFS = Path.home() / ".claude/LifeOS/USER/SKILLCUSTOMIZATIONS/Trading/PREFERENCES.md"
OUT = Path(__file__).resolve().parent.parent / "scripts/local/baf-rconfig.das"
SLOTS = 3
# | **LIVE (ACCOUNTID)** | **$NN** | ...
ROW = re.compile(r"^\|\s*\*\*(LIVE|SIM) \(([A-Z0-9]+)\)\*\*\s*\|\s*\*\*\$(\d+(?:\.\d+)?)\*\*", re.M)


def rows(text: str) -> list[tuple[str, str, float]]:
    """Rows of the first table after the R-CONFIG heading. Every bold account row in that table
    must parse, or this fails: a silently skipped row would leave an account with no R."""
    start = text.find("R-CONFIG")
    if start < 0:
        raise ValueError("no R-CONFIG heading")
    table, seen = [], False
    for line in text[start:].splitlines():
        if line.startswith("|"):
            seen = True
            table.append(line)
        elif seen:
            break
    block = "\n".join(table)
    found = [(kind, acct, float(r)) for kind, acct, r in ROW.findall(block)]
    account_rows = [l for l in table if l.lstrip("| ").startswith("**")]
    if len(found) != len(account_rows):
        raise ValueError(f"{len(account_rows)} account rows in R-CONFIG, {len(found)} parsed")
    ids = [acct for _, acct, _ in found]
    if len(set(ids)) != len(ids):
        raise ValueError("an account appears twice in R-CONFIG")
    return found


def render(found: list[tuple[str, str, float]]) -> str:
    lines = ["// baf-rconfig.das: generated by tools/baf_rconfig.py from PREFERENCES R-CONFIG.",
             "// PRIVATE: holds account IDs. Never commit, never post. Re-generate, do not edit."]
    for n in range(1, SLOTS + 1):
        if n <= len(found):
            kind, acct, r = found[n - 1]
            lines.append(f'$BAF_ACCT{n} = "{acct}";   // {kind}')
            lines.append(f"$BAF_R{n} = {r:g};")
        else:
            lines.append(f'$BAF_ACCT{n} = "none";')
            lines.append(f"$BAF_R{n} = 0;")
    lines.append('MsgLog("BAF R-CONFIG loaded");')
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="print the slots with IDs masked; write nothing")
    a = ap.parse_args()
    try:
        found = rows(PREFS.read_text())
    except OSError as exc:
        print(f"cannot read R-CONFIG: {exc}", file=sys.stderr)
        return 2
    except ValueError as exc:
        print(f"R-CONFIG not usable: {exc}", file=sys.stderr)
        return 1
    if not found:
        print(f"no R-CONFIG rows found in {PREFS}", file=sys.stderr)
        return 1
    if len(found) > SLOTS:
        print(f"{len(found)} accounts in R-CONFIG; the script has {SLOTS} slots", file=sys.stderr)
        return 1
    if any(r <= 0 for _, _, r in found):
        print("an R-CONFIG row has R <= 0", file=sys.stderr)
        return 1
    if a.check:
        for n, (kind, acct, r) in enumerate(found, 1):
            print(f"slot {n}: {kind} ...{acct[-2:]}  R={r:g}")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(found))
    print(f"wrote {OUT.relative_to(OUT.parent.parent.parent)} ({len(found)} account(s))")
    return 0


if __name__ == "__main__":
    sys.exit(main())
